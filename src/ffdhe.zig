pub const public_key_len = 256;
pub const shared_secret_len = 256;

pub const KeyPair = struct {
    modulus: Modulus,
    private_key: Fe,
    public_key: [public_key_len]u8,

    fn privateKeyFromSeed(modulus: Modulus, seed: [32]u8) !Fe {
        const two = try Fe.fromPrimitive(u8, modulus, 2);
        const max = modulus.sub(modulus.one(), two);
        var counter: u32 = 0;
        while (true) : (counter += 1) {
            var expanded: [256]u8 = undefined;
            @memset(&expanded, 0);
            var hasher = crypto.hash.sha2.Sha256.init(.{});
            hasher.update(&seed);
            var ctr: [4]u8 = undefined;
            mem.writeInt(u32, &ctr, counter, .little);
            hasher.update(&ctr);
            hasher.final(expanded[224..256]);
            const sk = Fe.fromBytes(modulus, &expanded, .big) catch continue;
            if (sk.compare(two) != .gt) continue;
            if (sk.compare(max) == .gt) continue;
            return sk;
        }
    }

    pub fn generateDeterministic(seed: [32]u8) !KeyPair {
        const modulus = try Modulus.fromBytes(&ffdhe2048_prime, .big);
        const two = try Fe.fromPrimitive(u8, modulus, 2);
        const private_key = try privateKeyFromSeed(modulus, seed);
        const public_fe = try modulus.pow(two, private_key);
        var public_key: [public_key_len]u8 = undefined;
        try public_fe.toBytes(&public_key, .big);
        return .{ .modulus = modulus, .private_key = private_key, .public_key = public_key };
    }

    pub fn sharedSecret(self: KeyPair, peer_public: []const u8) ![shared_secret_len]u8 {
        if (peer_public.len != public_key_len) return error.TlsIllegalParameter;
        const peer = try Fe.fromBytes(self.modulus, peer_public, .big);
        const two = try Fe.fromPrimitive(u8, self.modulus, 2);
        if (peer.compare(two) != .gt) return error.TlsIllegalParameter;
        const max = self.modulus.sub(self.modulus.one(), two);
        if (peer.compare(max) != .lt) return error.TlsIllegalParameter;
        const shared = try self.modulus.pow(peer, self.private_key);
        var out: [shared_secret_len]u8 = undefined;
        try shared.toBytes(&out, .big);
        return out;
    }
};

const testing = std.testing;

test "ffdhe2048 roundtrip" {
    var seed_a: [32]u8 = undefined;
    var seed_b: [32]u8 = undefined;
    @memset(&seed_a, 0x11);
    @memset(&seed_b, 0x22);
    const a = try KeyPair.generateDeterministic(seed_a);
    const b = try KeyPair.generateDeterministic(seed_b);
    const sa = try a.sharedSecret(&b.public_key);
    const sb = try b.sharedSecret(&a.public_key);
    try testing.expectEqualSlices(u8, &sa, &sb);
}
